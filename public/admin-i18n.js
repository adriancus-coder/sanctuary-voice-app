  const LS_KEY = "sanctuary_admin_ui_lang";
  function getLang() {
    const saved = localStorage.getItem(LS_KEY);
    return (saved && DICT[saved]) ? saved : "ro";
  }
  function applyLang(lang) {
    if (!DICT[lang]) lang = "ro";
    const d = DICT[lang];
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      const k = el.getAttribute("data-i18n");
      if (d[k] != null) el.textContent = d[k];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      const k = el.getAttribute("data-i18n-placeholder");
      if (d[k] != null) el.setAttribute("placeholder", d[k]);
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      const k = el.getAttribute("data-i18n-title");
      if (d[k] != null) el.setAttribute("title", d[k]);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      const k = el.getAttribute("data-i18n-aria");
      if (d[k] != null) el.setAttribute("aria-label", d[k]);
    });
    document.documentElement.setAttribute("lang", lang);
    localStorage.setItem(LS_KEY, lang);
    document.querySelectorAll(".ui-lang-switch button").forEach(function (b) {
      b.classList.toggle("on", b.getAttribute("data-lang") === lang);
    });
  }
  window.adminI18n = { apply: applyLang, get: getLang, dict: DICT };
  document.addEventListener("DOMContentLoaded", function () {
    applyLang(getLang());
    document.querySelectorAll(".ui-lang-switch button").forEach(function (b) {
      b.addEventListener("click", function () { applyLang(b.getAttribute("data-lang")); });
    });
  });
